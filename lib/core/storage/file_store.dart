import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:personal_life_manager/core/error/failure.dart';
import 'package:personal_life_manager/core/error/result.dart';
import 'package:uuid/uuid.dart';

/// Stores user files (documents, attachments, receipts) in the app's private
/// directory under UUID names. Callers keep the original name as metadata;
/// it never reaches the file system.
class FileStore {
  FileStore(this._root, [this._uuid = const Uuid()]);

  final Directory _root;
  final Uuid _uuid;

  /// Copies [source] into the store and returns the stored key
  /// (`<uuid>.<ext>`), which is what records persist.
  Future<Result<String>> importFile(File source) {
    final key = _newKey(p.extension(source.path));
    return guard<String, FileSystemException>(() async {
      await _atomicWrite(key, (tmp) => source.copy(tmp.path));
      return key;
    }, (e) => StorageFailure('import failed (${e.osError?.errorCode})'));
  }

  Future<Result<String>> writeBytes(List<int> bytes, {required String ext}) {
    final key = _newKey(ext);
    return guard<String, FileSystemException>(() async {
      await _atomicWrite(key, (tmp) => tmp.writeAsBytes(bytes, flush: true));
      return key;
    }, (e) => StorageFailure('write failed (${e.osError?.errorCode})'));
  }

  /// Resolves a stored key to its file, or [NotFoundFailure] if missing.
  Future<Result<File>> resolve(String key) async {
    if (!isValidKey(key)) return const Err(ValidationFailure('bad key'));
    final file = File(_pathFor(key));
    return file.existsSync()
        ? Ok(file)
        : const Err(NotFoundFailure('file missing'));
  }

  bool exists(String key) =>
      isValidKey(key) && File(_pathFor(key)).existsSync();

  /// Copies [source] in under an existing [key] (restoring a backup keeps
  /// the keys its records refer to). Doesn't overwrite.
  Future<Result<void>> importAs(File source, String key) {
    if (!isValidKey(key)) {
      return Future.value(const Err(ValidationFailure('bad key')));
    }
    return guard<void, FileSystemException>(() async {
      if (File(_pathFor(key)).existsSync()) return;
      await _atomicWrite(key, (tmp) => source.copy(tmp.path));
    }, (e) => StorageFailure('restore failed (${e.osError?.errorCode})'));
  }

  /// Deletes a stored file. Deleting a missing file succeeds (idempotent).
  Future<Result<void>> delete(String key) {
    if (!isValidKey(key)) {
      return Future.value(const Err(ValidationFailure('bad key')));
    }
    return guard<void, FileSystemException>(() async {
      final file = File(_pathFor(key));
      if (file.existsSync()) await file.delete();
    }, (e) => StorageFailure('delete failed (${e.osError?.errorCode})'));
  }

  String _newKey(String ext) {
    final e = ext.toLowerCase();
    final normalised = e.isEmpty || e.startsWith('.') ? e : '.$e';
    return '${_uuid.v4()}$normalised';
  }

  String _pathFor(String key) => p.join(_root.path, key);

  /// Writes to a `.part` file first so a crash never leaves a truncated file
  /// under a valid key.
  Future<void> _atomicWrite(
    String key,
    Future<void> Function(File tmp) write,
  ) async {
    final tmp = File('${_pathFor(key)}.part');
    try {
      await write(tmp);
      await tmp.rename(_pathFor(key));
    } on FileSystemException {
      if (tmp.existsSync()) await tmp.delete();
      rethrow;
    }
  }

  // Keys are generated by this class; anything else (e.g. `../`) is rejected
  // so a corrupt record can't address files outside the store.
  static final _keyPattern = RegExp(r'^[0-9a-f-]{36}(\.[a-z0-9]{1,8})?$');

  static bool isValidKey(String key) => _keyPattern.hasMatch(key);
}
